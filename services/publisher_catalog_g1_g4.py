def _variation_levels(difficulties: tuple[str, ...]) -> tuple[int, ...]:
    levels: set[int] = set()
    for d in difficulties:
        levels.update(VARIATION_BY_DIFFICULTY.get(d, (1,)))
    return tuple(sorted(levels))


def _dedupe(items: tuple[str, ...]) -> tuple[str, ...]:
    return tuple(dict.fromkeys(items))


def _normalize_question_types(grade: int, qtypes: tuple[str, ...]) -> tuple[str, ...]:
    mapping = _MIDDLE_TO_LOWER if grade <= 2 else _LOWER_TO_MIDDLE
    return _dedupe(tuple(mapping.get(item, item) for item in qtypes))


def build_catalogs() -> list[dict[str, Any]]:
    """Expand the compact data into the full, documented catalog structure."""
    catalogs: list[dict[str, Any]] = []
    for (grade, publisher, semester, volume, verification_status,
         source_urls, note, units) in _ALL_CATALOGS:
        catalog_units = []
        for unit_order, (official_name, domain, subunits) in enumerate(units, start=1):
            subunit_records = []
            for idx, (name, focus, errors, qtypes, difficulties) in enumerate(subunits, start=1):
                subunit_id = (
                    f"G{grade}-{_PUBLISHER_ABBR[publisher]}-"
                    f"{_semester_key(semester)}-U{unit_order}-S{idx}"
                )
                subunit_records.append({
                    "subunit_id": subunit_id,
                    "standard_name": name,
                    "publisher_original_unit": official_name,
                    "learning_focus": focus,
                    "prerequisite": [],
                    "common_errors": list(errors.split("、")) if errors else [],
                    "question_types": _normalize_question_types(grade, qtypes),
                    "difficulty_range": _dedupe(difficulties),
                    "variation_levels": _variation_levels(difficulties),
                })
            catalog_units.append({
                "unit_order": unit_order,
                "official_unit_name": official_name,
                "domain": domain,
                "subunits": subunit_records,
            })
        catalogs.append({
            "grade": grade,
            "publisher": publisher,
            "semester": semester,
            "volume": volume,
            "verification_status": verification_status,
            "source_url": list(source_urls),
            "source_type": "publisher_aligned_source (course plan / course map / assessment TOC)",
            "note": note,
            "units": catalog_units,
        })
    return catalogs


_CATALOG_INDEX: dict[tuple[int, str, str], dict[str, Any]] | None = None


def get_catalog(grade: int, publisher: str, semester: str) -> dict[str, Any] | None:
    global _CATALOG_INDEX
    if _CATALOG_INDEX is None:
        _CATALOG_INDEX = {
            (c["grade"], c["publisher"], c["semester"]): c
            for c in build_catalogs()
        }
    return _CATALOG_INDEX.get((grade, publisher, semester))


def all_catalogs() -> list[dict[str, Any]]:
    return build_catalogs()
