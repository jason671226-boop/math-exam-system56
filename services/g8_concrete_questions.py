def concrete_questions(skill_id: str, level: int) -> tuple[dict[str, Any], ...]:
    """Apply a reasoning contract without changing difficulty by number size."""
    base = _base_concrete_questions(skill_id)
    if level <= 1:
        return base
    transformed: list[dict[str, Any]] = []
    for row in base:
        item = dict(row)
        if level == 2:
            item["question"] += " 寫出你選用的公式或判準，再計算。"
            item["working"] += " 先說明選用此方法的理由，再依序計算。"
        elif level == 3:
            item["question"] += " 完成後再用代回、逆運算或等價關係驗證結果。"
            item["working"] += " 求得結果後，以原條件反向檢查，確認每一條件都成立。"
        else:
            item["question"] += " 比較兩種可行策略，選擇較有效率者求解，並說明另一策略仍可行或不適用的原因。"
            item["working"] += " 先比較直接計算與結構化方法；採較短的路徑求解，再用另一條關係交叉檢核。"
        transformed.append(item)
    return tuple(transformed)
