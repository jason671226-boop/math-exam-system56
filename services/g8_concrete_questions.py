"""Deterministic, student-ready G8 question blueprints.

Each family returns five different problem structures.  The values are kept
small enough for hand calculation; difficulty is expressed by the requested
reasoning structure, not merely by inflating numbers.
"""

from __future__ import annotations

from typing import Any


def _items(*rows: tuple[str, str, str]) -> tuple[dict[str, Any], ...]:
    return tuple({"question": q, "answer": a, "working": w} for q, a, w in rows)


